        // Supabase keys come from each developer's own local.properties (never committed).
        // A missing file or key gives an empty string, so the app still builds without them.
        val props = Properties().apply {
            val file = rootProject.file("local.properties")
            if (file.exists()) file.inputStream().use { load(it) }
        }
        val supabaseUrl = props.getProperty("SUPABASE_URL") ?: ""
        val supabaseKey = props.getProperty("SUPABASE_PUBLISHABLE_KEY") ?: ""
        buildConfigField("String", "SUPABASE_URL", "\"$supabaseUrl\"")
        buildConfigField("String", "SUPABASE_PUBLISHABLE_KEY", "\"$supabaseKey\"")
